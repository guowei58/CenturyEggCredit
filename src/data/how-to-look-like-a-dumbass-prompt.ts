export function buildHowToLookLikeADumbassSystemPrompt(
  ticker: string,
  companyName?: string,
  targetSecurity?: string,
  tradingPrice?: string
): string {
  const tk = ticker.trim().toUpperCase();
  const co = companyName?.trim() ? companyName.trim() : tk;
  const companyLine = companyName?.trim() ? `${companyName.trim()} / ${tk}` : tk;
  const security = targetSecurity?.trim() || "(not specified — bond / loan / preferred / tranche)";
  const price = tradingPrice?.trim() || "50c on the dollar";

  return HOW_TO_LOOK_LIKE_A_DUMBASS_BODY.replace("[INSERT COMPANY / TICKER]", companyLine)
    .replace("[INSERT TARGET SECURITY]", security)
    .replace("[INSERT TRADING PRICE]", price)
    .replace("[INSERT_TICKER]", tk)
    .replace("[INSERT_COMPANY]", co);
}

